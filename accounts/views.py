@api_view(['GET'])
@permission_classes([IsAuthenticated])
def dynamic_profile_view(request):
    """
    Fetches the profile info and aggregates generation metrics for the authenticated user.
    """
    user = request.user
    
    # Count the total scripts generated by this user using the related_name defined earlier
    total_generations = user.scripts.count()
    
    return Response({
        "username": user.username,
        "email": user.email if user.email else "no-email@creator.com",
        "date_joined": user.date_joined.strftime("%B %d, %Y"),
        "total_generations": total_generations
    }, status=status.HTTP_200_OK)