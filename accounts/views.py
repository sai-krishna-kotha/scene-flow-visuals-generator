@api_view(['POST'])
@permission_classes([AllowAny])  # Anyone should be able to reach the login screen
def login_view(request):
    username = request.data.get('username')
    password = request.data.get('password')

    if not username or not password:
        return Response({"error": "Please provide both username and password"}, status=status.HTTP_400_BAD_REQUEST)

    user = authenticate(request, username=username, password=password)
    
    if user is not None:
        login(request, user)  # This hooks into Django's session framework and sends a session cookie
        return Response({"message": "Login successful", "username": user.username}, status=status.HTTP_200_OK)
    
    return Response({"error": "Invalid username or password, bro."}, status=status.HTTP_401_UNAUTHORIZED)


@api_view(['POST'])
@permission_classes([IsAuthenticated])  # Only logged-in users can log out
def logout_view(request):
    logout(request)
    return Response({"message": "Successfully logged out"}, status=status.HTTP_200_OK)


