from django.shortcuts import render
from django.contrib.auth import authenticate, login, logout
from django.contrib.auth.models import User
from rest_framework.decorators import api_view, permission_classes
from rest_framework.permissions import AllowAny, IsAuthenticated
from rest_framework.response import Response
from rest_framework import status

# Add this new endpoint to accounts/views.py
from django.db import IntegrityError

@api_view(['POST'])
@permission_classes([AllowAny])  # Anyone can access the registration page
def signup_view(request):
    username = request.data.get('username')
    password = request.data.get('password')
    confirm_password = request.data.get('confirm_password')

    # 1. Basic Validation
    if not username or not password:
        return Response({"error": "Username and password cannot be empty, bro."}, status=status.HTTP_400_BAD_REQUEST)
    
    if password != confirm_password:
        return Response({"error": "Passwords do not match!"}, status=status.HTTP_400_BAD_REQUEST)

    if len(password) < 6:
        return Response({"error": "Password must be at least 6 characters long."}, status=status.HTTP_400_BAD_REQUEST)

    # 2. Check if username exists
    if User.objects.filter(username=username).exists():
        return Response({"error": "This username is already taken. Try another one!"}, status=status.HTTP_400_BAD_REQUEST)

    # 3. Create user securely
    try:
        # CRITICAL: Use create_user, NOT create(). create_user hashes the password!
        user = User.objects.create_user(username=username, password=password)
        
        # Smooth UX: Auto-login the user immediately after signing up
        login(request, user)
        
        return Response({"message": "User registered successfully!", "username": user.username}, status=status.HTTP_201_CREATED)
    except Exception as e:
        return Response({"error": f"Database insertion failed: {e}"}, status=status.HTTP_500_INTERNAL_SERVER_ERROR)


